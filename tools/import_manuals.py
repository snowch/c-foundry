#!/usr/bin/env python3
"""Import pinned Linux man-pages, preserving roff source and per-page licences.

Build-time only. Runtime reads the committed bundle; mandoc 1.14.6 is required
only to regenerate it. Run with --mandoc PATH --source PATH.
"""
import argparse, hashlib, html, json, pathlib, re, shutil, subprocess
root=pathlib.Path(__file__).resolve().parent.parent
p=argparse.ArgumentParser();p.add_argument('--mandoc',required=True);p.add_argument('--source',required=True);a=p.parse_args()
src=pathlib.Path(a.source).resolve();mandoc=str(pathlib.Path(a.mandoc).resolve())
names='printf fprintf snprintf puts putchar fgets getchar fgetc scanf sscanf fopen fclose fread fwrite fflush ferror feof fseek ftell rewind remove rename setvbuf malloc calloc realloc free memcpy memmove memset memcmp strlen strcmp strncmp strcpy strncpy strchr strstr strtok strtol strtoul strtod isspace isalpha isdigit tolower toupper qsort bsearch assert perror strerror exit abort atexit strftime time clock_gettime setlocale localeconv sqrt pow isnan isfinite fenv stdio errno pthread_create pthread_join pthread_mutex_init pthread_mutex_lock pthread_mutex_unlock pthread_mutex_destroy pthread_cond_init pthread_cond_wait pthread_cond_signal pthread_cond_broadcast pthread_cond_destroy pthread_self pthread_equal sem_init sem_wait sem_post sem_destroy'.split()
entries=[(n,('2' if n in {'rename','time'} else '3')) for n in names]+[(n,'2') for n in ['fsync','open','read','write','close','fork','wait','pipe','mmap']]+[(n,'7') for n in ['pthreads','signal','feature_test_macros']]
out=root/'dist/manuals';(out/'source').mkdir(parents=True,exist_ok=True);(out/'licenses').mkdir(exist_ok=True)
native=root/'native/manuals';native.mkdir(parents=True,exist_ok=True)
for f in (src/'LICENSES').glob('*.txt'):shutil.copyfile(f,out/'licenses'/f.name);shutil.copyfile(f,native/f.name)
models={};manifest=[]
for name,section in entries:
 key=name+'.'+section;path=src/'man'/('man'+section)/key
 if not path.exists():
  candidates=list((src/'man').glob('man[237]/'+name+'.[237]'))
  if len(candidates)!=1:raise RuntimeError('Missing or ambiguous '+key)
  path=candidates[0];section=path.suffix[1:];key=name+'.'+section
 visited=set()
 while True:
  if path in visited:raise RuntimeError('Alias cycle')
  visited.add(path);body=path.read_text();alias=re.fullmatch(r'\s*\.so\s+(\S+)\s*',body)
  if not alias:break
  path=src/'man'/alias[1]
 relative=path.relative_to(src).as_posix()
 rendered=subprocess.run([mandoc,'-Thtml','-Ofragment,man=#/manual/%N.%S',relative],cwd=src,capture_output=True,text=True,check=True).stdout
 rendered=re.sub(r'<table class="(?:head|foot)">.*?</table>','',rendered,flags=re.S)
 rendered=re.sub(r'<(/?)h1\b',r'<\1h2',rendered)
 rendered=re.sub(r'href="#(?!/)([^"]+)"',lambda m:'href="#/manual/'+key+'/'+m[1]+'"',rendered)
 # Section jumps use course routes, so opening a heading cannot lose the lesson.
 plain=subprocess.run([mandoc,'-Tascii','-Owidth=88',relative],cwd=src,capture_output=True,text=True,check=True).stdout
 while '\b' in plain:plain=re.sub('.\x08','',plain)
 summary=re.search(r'<h2[^>]*id="NAME".*?</h2>\s*<p[^>]*>(.*?)</p>',rendered,re.S)
 summary=html.unescape(re.sub('<[^>]+>','',summary[1])).strip() if summary else name
 summary=' '.join(summary.split())
 licences=re.findall(r'SPDX-License-Identifier:\s*([^\n]+)',body)
 (out/'source'/key).write_text(body);(native/(key+'.txt')).write_text(plain)
 models[key]={'name':name,'section':section,'summary':summary,'html':rendered,'source':relative,'license':licences[0].strip() if licences else 'See source notice'}
 manifest.append({'id':key,'source':relative,'sha256':hashlib.sha256(body.encode()).hexdigest(),'license':models[key]['license']})
# Leave unbundled SEE ALSO names readable; never send offline readers to a missing route.
for item in models.values():
 item['html']=re.sub(r'<a ([^>]*?)href="#/manual/([^"/]+)"([^>]*)>(.*?)</a>',lambda m:m[0] if m[2] in models else m[4],item['html'],flags=re.S)
 item['html']=re.sub(r'<a\b([^>]*?)\bhref="(https?://[^"]+)"([^>]*)>(.*?)</a>',lambda m:'<a '+m[1]+'href="'+m[2]+'"'+m[3]+' target="_blank" rel="noopener noreferrer">'+m[4]+' (internet required)</a>',item['html'],flags=re.S)
(root/'dist/manual-pages.js').write_text('// Generated by tools/import_manuals.py; upstream notices in manuals/.\nwindow.C_MANUAL_PAGES='+json.dumps(models,ensure_ascii=False,separators=(',',':'))+';\n')
(native/'index.json').write_text(json.dumps({k:{'summary':v['summary'],'file':k+'.txt'} for k,v in models.items()},indent=2)+'\n')
notice='''# Bundled Linux manual pages

Upstream: Linux man-pages 6.16, https://www.kernel.org/pub/linux/docs/man-pages/man-pages-6.16.tar.xz
Archive SHA256: 8e247abd75cd80809cfe08696c81b8c70690583b045749484b242fb43631d7a3
Rendered with mandoc 1.14.6 (ISC licence; build-time tool only).

Each page retains its original copyright and licence notice in source/. All
upstream licence texts are in licenses/. manifest.json identifies each page.
The HTML changes headings and cross-reference links for the course reader;
manual content is otherwise unchanged. Terminal copies only remove overstrike
formatting and wrap at 88 columns. This documentation has its own licences;
it is not relicensed under the course licence.

These manuals describe Linux/glibc contracts and extensions, not a promise of
support in the inline WASI compiler or the musl-based Browser Linux guest.
Use STANDARDS, feature-test requirements and the lesson's target when reading.
'''
(out/'NOTICE.md').write_text(notice);(out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');(native/'NOTICE.md').write_text(notice.replace('in source/','in dist/manuals/source/').replace('in licenses/','in dist/manuals/licenses/'))
print('Imported',len(models),'offline manual entries')
